// ========== 断点常量（唯一来源） ==========
// 全项目的屏幕宽度断点都定义在这里
// 以后要调整断点，只改这个文件，其他文件不用动
//
// 为什么要有两个断点，而不是一个？
// 因为屏幕宽度存在三种形态：
//   1. 手机（< 768）      → 窄屏，单手操作
//   2. 平板（768 ~ 1023） → 中间带，触摸操作但空间较大
//   3. 桌面（>= 1024）    → 宽屏，鼠标键盘操作
//
// 因此两个 hook 的判定是「互补但不同界」的：
//   useIsMobile()   → 宽度 < 768  为 true
//   useIsDesktop()  → 宽度 >= 1024 为 true
//   宽度落在 768~1023 时，两者都是 false（这是设计如此，不是 bug）

// 手机断点：小于这个宽度判定为手机
export const MOBILE_BREAKPOINT = 768

// 桌面断点：大于等于这个宽度判定为桌面
export const DESKTOP_BREAKPOINT = 1024

// ========== 使用约定 ==========
// 判断「该用哪套界面」时，请统一使用 useIsDesktop()
// 因为全局外壳 responsive-layout.tsx 就是用 useIsDesktop() 判定布局的
//   用 !isDesktop 得到「移动端」，这样你的组件和外壳永远一致
//   用 isMobile 会得到「严格意义的手机」，在平板宽度下会与外壳不一致
// 例：< 768 手机走移动界面，768~1023 平板也走移动界面，>= 1024 才走桌面界面
